# 小车编号到拓扑矩阵下标的映射
CAR_INDEX_MAP = {car_id: i for i, car_id in enumerate(ALL_CAR_IDS)}

# ------------------------------------------------------------------------------
# 通信拓扑默认矩阵（8x8）
# ------------------------------------------------------------------------------
# 行=源车，列=目标车；[i][j]=1 表示 j 能收到 i 的状态。默认全连通（对角线为 0）。
DEFAULT_COMMUNICATION_TOPOLOGY = [
    [0 if i == j else 1 for j in range(MAX_CARS)] for i in range(MAX_CARS)
]

